const (
	binderPath      = "github.com/microsoft/TypeScript/tsc/internal/binder"
	storeDir        = "tsc/internal/ast/store"
	utilitiesFile   = "utilities.go"
	manualFile      = "utilities_manual.go"
	generatedHeader = "// Code generated by tools/cmd/storetranslate. DO NOT EDIT."
)

// program is the loaded source: ast, store (without the utilities it is
// about to regenerate) and binder, in one type universe.
type program struct {
	root   string
	fset   *token.FileSet
	ast    *packages.Package
	store  *packages.Package
	binder *packages.Package
	all    []*packages.Package
	extra  []*packages.Package // the packages of loadWith's patterns
}

func load(root string) (*program, error) { return loadWith(root, nil) }

// loadWith loads the program with more files (overlay, absolute paths) and
// more packages (patterns relative to tsc), as the tests of the rules do.
func loadWith(root string, overlay map[string][]byte, patterns ...string) (*program, error) {
	tsc := filepath.Join(root, "tsc")
	utilities := filepath.Join(root, storeDir, utilitiesFile)
	fset := token.NewFileSet()
	cfg := &packages.Config{
		Dir:  tsc,
		Fset: fset,
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax | packages.NeedTypes | packages.NeedTypesInfo | packages.NeedImports | packages.NeedDeps,
		// The output is regenerated from nothing: the store package is read
		// without its current utilities, so that a stale or broken output
		// does not feed the next one. The names it lacks are reported as
		// type errors of package store, which are expected.
		Overlay: map[string][]byte{utilities: []byte("package store\n")},
	}
	for path, text := range overlay {
		cfg.Overlay[path] = text
	}
	pkgs, err := packages.Load(cfg, append([]string{astPath, storePath, binderPath}, patterns...)...)
	if err != nil {
		return nil, err
	}
	p := &program{root: root, fset: fset}
	packages.Visit(pkgs, nil, func(pkg *packages.Package) { p.all = append(p.all, pkg) })
	for _, pkg := range pkgs {
		switch pkg.PkgPath {
		case astPath:
			p.ast = pkg
		case storePath:
			p.store = pkg
		case binderPath:
			p.binder = pkg
		default:
			p.extra = append(p.extra, pkg)
		}
	}
	for _, pkg := range []*packages.Package{p.ast, p.binder} {
		if len(pkg.Errors) > 0 {
			return nil, fmt.Errorf("%s: %v", pkg.PkgPath, pkg.Errors[0])
		}
	}
	return p, nil
}

func run(root, binderOut, verbatim string) error {
	p, err := load(root)
	if err != nil {
		return err
	}
	u := &universe{ast: p.ast.Types, store: p.store.Types}
	manual, err := readManual(p, filepath.Join(root, storeDir, manualFile))
	if err != nil {
		return err
	}
	handWritten := storeFuncs(p)
	roots, err := utilityRoots(p, handWritten)
	if err != nil {
		return err
	}
	reached, report, err := reach(p, roots, manual)
	if err != nil {
		return err
	}
	out := &target{name: "store", inStore: true, funcs: map[string]bool{}, imports: map[string]string{}}
	for _, name := range reached {
		out.funcs[name] = true
	}
	for name := range handWritten {
		out.funcs[name] = true
	}
	tr := &translator{universe: u, fset: p.fset, src: p.ast.Types, info: p.ast.TypesInfo, out: out}
	decls := astFuncDecls(p)
	var outDecls []ast.Decl
	var comments []*ast.CommentGroup
	var problems strings.Builder
	for _, name := range reached {
		if _, ok := manual[name]; ok {
			continue
		}
		d := decls[name]
		f := tr.newFn(d)
		outDecls = append(outDecls, f.funcDecl(d))
		comments = append(comments, commentsIn(p, d)...)
		if len(f.problems) > 0 {
			problems.WriteString(problemsText(name, f.problems))
		}
	}
	if problems.Len() > 0 {
		return fmt.Errorf("the rules do not translate these functions; write them in %s (P2):\n%s", manualFile, problems.String())
	}
	src, err := render(p.fset, "store", out.imports, outDecls, comments, utilitiesHeader(report))
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(root, storeDir, utilitiesFile), src, 0o644); err != nil {
		return err
	}
	fmt.Printf("wrote %s: %d functions translated, %d P2 (%s), %d roots\n", filepath.Join(storeDir, utilitiesFile), len(outDecls), len(manual), manualFile, len(roots))
	if binderOut != "" {
		return binderTrial(p, u, binderOut, verbatim, out.funcs)
	}
	return nil
}

// utilitiesHeader is the comment at the top of store/utilities.go.
func utilitiesHeader(report string) string {
	return generatedHeader + "\n\n" +
		"// The predicates and helpers of package ast that the Store code reads a node\n" +
		"// with, translated by the rules of tools/cmd/storetranslate (U2,\n" +
		"// internal/ast/docs/store-checker-design-20260923.md 2.1). The functions the\n" +
		"// rules do not cover are written by hand in utilities_manual.go (P2).\n" +
		"//\n" + report
}

// ── The roots and the reach ──

// storeFuncs are the package-level functions that package store has by hand
// outside the translated and P2 files: a call to one of them is a call to the
// Store version.
func storeFuncs(p *program) map[string]bool {
	names := map[string]bool{}
	for _, file := range p.store.Syntax {
		base := filepath.Base(p.fset.Position(file.Pos()).Filename)
		if base == utilitiesFile || base == manualFile || strings.HasSuffix(base, "_test.go") {
			continue
		}
		for _, d := range file.Decls {
			if fd, ok := d.(*ast.FuncDecl); ok && fd.Recv == nil {
				names[fd.Name.Name] = true
			}
		}
	}
	return names
}

// utilityRoots: the functions that store/utilities.go had in 7c (roots.txt,
// fixed, so that the roots do not depend on the output), and the ast
// functions that storebinder and storeparser call through store.
func utilityRoots(p *program, handWritten map[string]bool) ([]string, error) {
	astFuncs := astFuncDecls(p)
	roots := map[string]bool{}
	previous, err := os.ReadFile(filepath.Join(p.root, "tools/cmd/storetranslate/roots.txt"))
	if err != nil {
		return nil, err
	}
	for _, line := range strings.Split(string(previous), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if _, ok := astFuncs[line]; !ok {
			return nil, fmt.Errorf("roots.txt: %s is not a function of package ast", line)
		}
		roots[line] = true
	}
	callRe := regexp.MustCompile(`\bstore\.([A-Z]\w*)\(`)
	for _, dir := range []string{"tsc/internal/storebinder", "tsc/internal/storeparser"} {
		files, _ := filepath.Glob(filepath.Join(p.root, dir, "*.go"))
		for _, file := range files {
			if strings.HasSuffix(file, "_test.go") {
				continue
			}
			text, err := os.ReadFile(file)
			if err != nil {
				return nil, err
			}
			for _, m := range callRe.FindAllStringSubmatch(string(text), -1) {
				if _, ok := astFuncs[m[1]]; ok {
					roots[m[1]] = true
				}
			}
		}
	}
	var out []string
	for name := range roots {
		if handWritten[name] {
			return nil, fmt.Errorf("%s is a root and is written by hand outside %s", name, manualFile)
		}
		out = append(out, name)
	}
	sort.Strings(out)
	return out, nil
}

// astFuncDecls are the package-level functions (not methods) of package ast.
func astFuncDecls(p *program) map[string]*ast.FuncDecl {
	decls := map[string]*ast.FuncDecl{}
	for _, file := range p.ast.Syntax {
		for _, d := range file.Decls {
			if fd, ok := d.(*ast.FuncDecl); ok && fd.Recv == nil && fd.Name.Name != "init" && fd.Name.Name != "_" {
				decls[fd.Name.Name] = fd
			}
		}
	}
	return decls
}

// reach is the set of functions of package ast to put in the output: from
// the roots, every package-level function of package ast that a reached
// function names in its body, called or as a value. A function value is
// followed only where a reached function names it: a value that the output
// calls comes from the output itself, or from its caller, whose own
// translation must name it (a missing one does not compile). A P2 function's
// Pointer body is not followed; the ast functions that its Store body calls
// are followed instead. The result is in source order.
func reach(p *program, roots []string, manual map[string]*manualFunc) ([]string, string, error) {
	decls := astFuncDecls(p)
	seen := map[string]bool{}
	from := map[string]string{}
	var queue []string
	u := &universe{ast: p.ast.Types, store: p.store.Types}
	add := func(name, parent string) {
		if d, ok := decls[name]; ok {
			if fun, ok := p.ast.TypesInfo.Defs[d.Name].(*types.Func); ok && keptInAST(u, fun) {
				return
			}
		}
		if !seen[name] && !ruleRewritten[name] {
			seen[name] = true
			from[name] = parent
			queue = append(queue, name)
		}
	}
	for _, name := range roots {
		if _, ok := decls[name]; !ok {
			return nil, "", fmt.Errorf("no function ast.%s", name)
		}
		add(name, "")
	}
	for len(queue) > 0 {
		name := queue[0]
		queue = queue[1:]
		var names []string
		if m, ok := manual[name]; ok {
			names = m.callees
		} else {
			names = namedFuncs(p, decls[name])
		}
		for _, callee := range names {
			if _, ok := decls[callee]; ok {
				add(callee, name)
			}
		}
	}
	var out []string
	for name := range seen {
		out = append(out, name)
	}
	sort.Slice(out, func(i, j int) bool { return sourceLess(p.fset, decls[out[i]], decls[out[j]]) })
	if os.Getenv("STORETRANSLATE_REACH") != "" {
		for _, name := range out {
			fmt.Fprintf(os.Stderr, "reach %s <- %s\n", name, from[name])
		}
	}
	report := fmt.Sprintf("// Reach: %d roots, %d functions of package ast that the roots name in\n"+
		"// their bodies, called or as a value, transitively.\n", len(roots), len(out))
	return out, report, nil
}

// sourceLess orders declarations by file name, then offset: the file order
// of a FileSet is the parse order, which go/packages does not fix.
func sourceLess(fset *token.FileSet, a, b ast.Node) bool {
	pa, pb := fset.Position(a.Pos()), fset.Position(b.Pos())
	if pa.Filename != pb.Filename {
		return pa.Filename < pb.Filename
	}
	return pa.Offset < pb.Offset
}

// namedFuncs are the package-level functions of package ast that decl names
// in its body, closures included, called or as a value. (An instantiation
// names its generic function.)
func namedFuncs(p *program, decl *ast.FuncDecl) []string {
	var out []string
	ast.Inspect(decl.Body, func(n ast.Node) bool {
		id, ok := n.(*ast.Ident)
		if !ok {
			return true
		}
		if fn, ok := p.ast.TypesInfo.Uses[id].(*types.Func); ok && fn.Pkg() == p.ast.Types && fn.Type().(*types.Signature).Recv() == nil {
			out = append(out, fn.Origin().Name())
		}
		return true
	})
	return out
}

// ruleRewritten are the ast functions whose calls a rule rewrites as a
// whole: they are never called in the output.
var ruleRewritten = map[string]bool{"GetSourceFileOfNode": true, "GetNodeId": true}

// ── P2 ──

type manualFunc struct {
	name    string
	hash    string
	file    string // the Pointer function's file, relative to tsc/internal/ast
	callees []string
}

var hashRe = regexp.MustCompile(`^// storetranslate:pointer-hash ([0-9a-f]{16}) (\S+):(\S+)$`)

// readManual reads the P2 functions and checks each hash against the
// Pointer function it replaces: a change there stops the translation.
func readManual(p *program, path string) (map[string]*manualFunc, error) {
	text, err := os.ReadFile(path)
	if err != nil {
		if os.IsNotExist(err) {
			return map[string]*manualFunc{}, nil
		}
		return nil, err
	}
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, path, text, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	decls := astFuncDecls(p)
	out := map[string]*manualFunc{}
	var errs []string
	for _, d := range file.Decls {
		fd, ok := d.(*ast.FuncDecl)
		if !ok || fd.Recv != nil {
			continue
		}
		var m *manualFunc
		if fd.Doc != nil {
			for _, c := range fd.Doc.List {
				if sub := hashRe.FindStringSubmatch(c.Text); sub != nil {
					m = &manualFunc{name: fd.Name.Name, hash: sub[1], file: sub[2]}
					if sub[3] != fd.Name.Name {
						errs = append(errs, fmt.Sprintf("%s: the hash names %s", fd.Name.Name, sub[3]))
					}
				}
			}
		}
		if m == nil {
			errs = append(errs, fmt.Sprintf("%s: no storetranslate:pointer-hash line", fd.Name.Name))
			continue
		}
		pd, ok := decls[m.name]
		if !ok {
			errs = append(errs, fmt.Sprintf("%s: not a function of package ast", m.name))
			continue
		}
		if got := filepath.Base(p.fset.Position(pd.Pos()).Filename); got != m.file {
			errs = append(errs, fmt.Sprintf("%s: the Pointer function is in %s, not %s", m.name, got, m.file))
		}
		if got := pointerHash(p, pd); got != m.hash {
			errs = append(errs, fmt.Sprintf("%s: the Pointer function changed (hash %s, recorded %s): check the P2 version against it and update the hash", m.name, got, m.hash))
		}
		ast.Inspect(fd.Body, func(n ast.Node) bool {
			if id, ok := n.(*ast.Ident); ok {
				m.callees = append(m.callees, id.Name)
			}
			return true
		})
		out[m.name] = m
	}
	if len(errs) > 0 {
		sort.Strings(errs)
		return nil, fmt.Errorf("%s:\n  %s", manualFile, strings.Join(errs, "\n  "))
	}
	return out, nil
}

func printHashes(root, names string) error {
	p, err := load(root)
	if err != nil {
		return err
	}
	decls := astFuncDecls(p)
	for _, name := range strings.Split(names, ",") {
		d, ok := decls[name]
		if !ok {
			return fmt.Errorf("%s is not a function of package ast", name)
		}
		fmt.Printf("// storetranslate:pointer-hash %s %s:%s\n", pointerHash(p, d), filepath.Base(p.fset.Position(d.Pos()).Filename), name)
	}
	return nil
}

// pointerHash is the first 16 hex digits of the sha256 of a Pointer
// function's source, from func to the closing brace (the doc comment is not
// part of it).
func pointerHash(p *program, d *ast.FuncDecl) string {
	sum := sha256.Sum256([]byte(sourceOf(p.fset, d.Pos(), d.End())))
	return hex.EncodeToString(sum[:])[:16]
}

func sourceOf(fset *token.FileSet, from, to token.Pos) string {
	file := fset.File(from)
	text, err := os.ReadFile(file.Name())
	if err != nil {
		panic(err)
	}
	return string(text[file.Offset(from):file.Offset(to)])
}

// ── Output ──

// commentsIn are the comment groups of a declaration, its doc included.
func commentsIn(p *program, d ast.Node) []*ast.CommentGroup {
	from := d.Pos()
	if fd, ok := d.(*ast.FuncDecl); ok && fd.Doc != nil {
		from = fd.Doc.Pos()
	}
	for _, file := range p.all {
		for _, f := range file.Syntax {
			if f.FileStart <= d.Pos() && d.Pos() < f.FileEnd {
				var out []*ast.CommentGroup
				for _, c := range f.Comments {
					if c.Pos() >= from && c.End() <= d.End() {
						out = append(out, c)
					}
				}
				return out
			}
		}
	}
	return nil
}

// render prints the declarations in order with their comments, then formats
// the file.
func render(fset *token.FileSet, pkg string, imports map[string]string, decls []ast.Decl, comments []*ast.CommentGroup, header string) ([]byte, error) {
	var body bytes.Buffer
	cfg := &printer.Config{Mode: printer.UseSpaces | printer.TabIndent, Tabwidth: 8}
	for _, d := range decls {
		var own []*ast.CommentGroup
		from, to := d.Pos(), d.End()
		if fd, ok := d.(*ast.FuncDecl); ok && fd.Doc != nil {
			from = fd.Doc.Pos()
			fd.Doc = nil // printed from the comment list instead
		}
		for _, c := range comments {
			if c.Pos() >= from && c.End() <= to {
				own = append(own, c)
			}
		}
		if err := cfg.Fprint(&body, fset, &printer.CommentedNode{Node: d, Comments: own}); err != nil {
			return nil, err
		}
		body.WriteString("\n\n")
	}
	var out bytes.Buffer
	out.WriteString(header)
	fmt.Fprintf(&out, "\npackage %s\n\n", pkg)
	// The standard library first, then the rest, as goimports groups them.
	var std, other []string
	for path := range imports {
		if strings.Contains(strings.Split(path, "/")[0], ".") {
			other = append(other, path)
		} else {
			std = append(std, path)
		}
	}
	slices.Sort(std)
	slices.Sort(other)
	if len(std)+len(other) > 0 {
		out.WriteString("import (\n")
		for _, path := range std {
			fmt.Fprintf(&out, "\t%q\n", path)
		}
		if len(std) > 0 && len(other) > 0 {
			out.WriteString("\n")
		}
		for _, path := range other {
			fmt.Fprintf(&out, "\t%q\n", path)
		}
		out.WriteString(")\n\n")
	}
	out.Write(body.Bytes())
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return out.Bytes(), fmt.Errorf("format: %w", err)
	}
	return formatted, nil
}
