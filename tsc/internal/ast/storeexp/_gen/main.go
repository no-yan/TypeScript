//go:build ignore

// The storeexp generator (EXPERIMENT; see ../doc.go). It reads the member
// declarations of tools/scripts/tsc/ast.json and the Go types of internal/ast,
// and writes the shape tables, ForEachChild and the Pointer-to-Store converter.
//
//	cd tsc && go run internal/ast/storeexp/_gen/main.go
package main

import (
	"encoding/json"
	"fmt"
	"go/constant"
	"go/format"
	"go/types"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"unicode"
	"unicode/utf8"

	"golang.org/x/tools/go/packages"
)

const (
	astPackage = "github.com/microsoft/TypeScript/tsc/internal/ast"
	schemaPath = "../tools/scripts/tsc/ast.json"
	outDir     = "internal/ast/storeexp"
	header     = "// Code generated by internal/ast/storeexp/_gen (EXPERIMENT). DO NOT EDIT.\n\n//go:build storeexp\n\npackage storeexp\n\n"
)

// memberOverrides replaces the ast.json member order for definitions whose
// Pointer ForEachChild is hand-written in internal/ast/ast.go. The order must be
// the order in which that ForEachChild visits.
var memberOverrides = map[string][]string{
	"SourceFile": {"Statements", "EndOfFileToken"},
	// The Pointer version visits TypeExpression before name when !IsNameFirst.
	// A fixed shape cannot express that. JSDoc is never converted, so the
	// name-first order is unobservable here.
	"JSDocParameterOrPropertyTag": {"TagName", "name", "TypeExpression", "Comment"},
}

// roleOverrides removes a kind from a polymorphic slot table where the member
// exists but the Pointer accessor of the same name does not return it.
var roleOverrides = map[string][]string{
	// (*ast.Node).Expression panics on these kinds.
	"Expression": {"DefaultClause", "TypeParameter", "SyntheticReferenceExpression"},
}

type definition struct {
	Kind    json.RawMessage `json:"kind"`
	Members []struct {
		Name string          `json:"name"`
		Type json.RawMessage `json:"type"`
	} `json:"members"`
}

type slotKind int

const (
	childSlot slotKind = iota
	nodeListSlot
	modifierListSlot
	rawListSlot
)

type slot struct {
	member string
	kind   slotKind
	read   string // Go expression on the typed struct d
}

type node struct {
	name  string // definition name, also the Go struct name
	kinds []string
	slots []slot
}

type kindEntry struct {
	name  string
	value int64
	node  *node
}

func main() {
	log.SetFlags(0)
	pkgs, err := packages.Load(&packages.Config{Mode: packages.NeedName | packages.NeedTypes}, astPackage)
	if err != nil || len(pkgs) != 1 || len(pkgs[0].Errors) != 0 {
		log.Fatalf("load %s: %v %v", astPackage, err, pkgs)
	}
	g := &generator{pkg: pkgs[0].Types}
	g.nodeType = g.pointerTo("Node")
	g.nodeListType = g.pointerTo("NodeList")
	g.modifierListType = g.pointerTo("ModifierList")

	raw, err := os.ReadFile(schemaPath)
	if err != nil {
		log.Fatal(err)
	}
	var schema struct {
		Nodes struct {
			Definitions map[string]definition `json:"definitions"`
		} `json:"nodes"`
	}
	if err := json.Unmarshal(raw, &schema); err != nil {
		log.Fatal(err)
	}
	for name, def := range schema.Nodes.Definitions {
		g.define(name, def)
	}
	if len(g.problems) != 0 {
		slices.Sort(g.problems)
		log.Fatalf("cannot generate:\n  %s", strings.Join(g.problems, "\n  "))
	}
	slices.SortFunc(g.kinds, func(a, b kindEntry) int { return int(a.value - b.value) })

	write("shapes_generated.go", g.shapes())
	write("foreach_generated.go", g.forEachChild())
	write("convert_generated.go", g.convert())
}

type generator struct {
	pkg                                      *types.Package
	nodeType, nodeListType, modifierListType types.Type
	kinds                                    []kindEntry // kinds with at least one slot
	problems                                 []string
}

func (g *generator) pointerTo(name string) types.Type {
	return types.NewPointer(g.pkg.Scope().Lookup(name).Type())
}

func (g *generator) problemf(format string, args ...any) {
	g.problems = append(g.problems, fmt.Sprintf(format, args...))
}

func (g *generator) define(name string, def definition) {
	obj := g.pkg.Scope().Lookup(name)
	if obj == nil {
		g.problemf("%s: no Go type", name)
		return
	}
	structPtr := types.NewPointer(obj.Type())
	n := &node{name: name}

	members := memberOverrides[name]
	if members == nil {
		for _, m := range def.Members {
			members = append(members, m.Name)
		}
	}
	for _, member := range members {
		field, _, _ := types.LookupFieldOrMethod(structPtr, true, g.pkg, member)
		v, ok := field.(*types.Var)
		if !ok {
			g.problemf("%s.%s: no Go field", name, member)
			continue
		}
		var kind slotKind
		switch t := v.Type(); {
		case types.Identical(t, g.nodeType):
			kind = childSlot
		case types.Identical(t, g.nodeListType):
			kind = nodeListSlot
		case types.Identical(t, g.modifierListType):
			kind = modifierListSlot
		case types.Identical(t, types.NewSlice(g.nodeType)):
			kind = rawListSlot
		default:
			continue
		}
		read := "d." + member
		if !v.Exported() {
			// A private member is read through its public accessor.
			accessor := capitalize(member)
			method, _, _ := types.LookupFieldOrMethod(structPtr, true, g.pkg, accessor)
			var sig *types.Signature
			if fn, ok := method.(*types.Func); ok {
				sig = fn.Type().(*types.Signature)
			}
			if sig == nil || sig.Params().Len() != 0 || sig.Results().Len() != 1 || !types.Identical(sig.Results().At(0).Type(), v.Type()) {
				g.problemf("%s.%s: private and no accessor %s() %s", name, member, accessor, v.Type())
				continue
			}
			read = "d." + accessor + "()"
		}
		n.slots = append(n.slots, slot{member, kind, read})
	}
	if len(n.slots) == 0 {
		return
	}
	if len(n.slots) > 16 {
		g.problemf("%s: %d slots do not fit the 16-bit list mask", name, len(n.slots))
	}

	n.kinds = kindNames(name, def)
	for _, kind := range n.kinds {
		c, ok := g.pkg.Scope().Lookup("Kind" + kind).(*types.Const)
		if !ok {
			g.problemf("%s: no constant Kind%s", name, kind)
			continue
		}
		value, _ := constant.Int64Val(c.Val())
		if value >= 512 {
			g.problemf("Kind%s = %d does not fit the 512-entry tables", kind, value)
		}
		g.kinds = append(g.kinds, kindEntry{kind, value, n})
	}
}

// kindNames resolves a definition to its kinds: the "kind" key, else a Kind
// member that lists SyntaxKind values, else the definition name. A definition
// that is generic over its kind (Token, KeywordExpression) has no slots and
// never gets here.
func kindNames(name string, def definition) []string {
	if names := stringOrList(def.Kind); names != nil {
		return names
	}
	for _, m := range def.Members {
		if m.Name != "Kind" {
			continue
		}
		var names []string
		for _, t := range stringOrList(m.Type) {
			if kind, ok := strings.CutPrefix(t, "SyntaxKind."); ok {
				names = append(names, kind)
			}
		}
		if names != nil {
			return names
		}
	}
	return []string{name}
}

func stringOrList(raw json.RawMessage) []string {
	var one string
	if json.Unmarshal(raw, &one) == nil && one != "" {
		return []string{one}
	}
	var many []string
	json.Unmarshal(raw, &many)
	return many
}

func capitalize(s string) string {
	r, size := utf8.DecodeRuneInString(s)
	return string(unicode.ToUpper(r)) + s[size:]
}

func (g *generator) shapes() string {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("import \"github.com/microsoft/TypeScript/tsc/internal/ast\"\n\n")
	b.WriteString("type shape struct {\n\tslots    uint8\n\tlistMask uint16 // bit i: slot i holds a list block index\n}\n\n")
	b.WriteString("var shapes = [512]shape{\n")
	for _, k := range g.kinds {
		var mask uint16
		for i, s := range k.node.slots {
			if s.kind != childSlot {
				mask |= 1 << i
			}
		}
		fmt.Fprintf(&b, "ast.Kind%s: {%d, %#b},\n", k.name, len(k.node.slots), mask)
	}
	b.WriteString("}\n\n")

	b.WriteString("// Slot of the member with that role; 0xFF = the kind does not have it.\n")
	b.WriteString("var nameSlot, expressionSlot, typeSlot, initializerSlot, bodySlot = roleSlots()\n\n")
	b.WriteString("func roleSlots() (name, expression, typ, initializer, body [512]uint8) {\n")
	b.WriteString("for _, t := range []*[512]uint8{&name, &expression, &typ, &initializer, &body} {\nfor i := range t {\nt[i] = 0xFF\n}\n}\n")
	for _, role := range []struct{ member, table string }{
		{"name", "name"}, {"Expression", "expression"}, {"Type", "typ"}, {"Initializer", "initializer"}, {"Body", "body"},
	} {
		for _, k := range g.kinds {
			if slices.Contains(roleOverrides[role.member], k.name) {
				continue
			}
			for i, s := range k.node.slots {
				if s.member == role.member && s.kind == childSlot {
					fmt.Fprintf(&b, "%s[ast.Kind%s] = %d\n", role.table, k.name, i)
				}
			}
		}
	}
	b.WriteString("return\n}\n")
	return b.String()
}

func (g *generator) forEachChild() string {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("import \"github.com/microsoft/TypeScript/tsc/internal/ast\"\n\n")
	b.WriteString("// The cases are in Kind order and cover every kind that has a slot.\n")
	b.WriteString("func (n Node) ForEachChild(v Visitor) bool {\nswitch n.h.kind {\n")
	for _, k := range g.kinds {
		fmt.Fprintf(&b, "case ast.Kind%s:\nreturn forEachChild%s(n, v)\n", k.name, k.node.name)
	}
	b.WriteString("}\nreturn false\n}\n")

	seen := map[*node]bool{}
	for _, k := range g.kinds {
		if seen[k.node] {
			continue
		}
		seen[k.node] = true
		fmt.Fprintf(&b, "\nfunc forEachChild%s(n Node, v Visitor) bool {\ns, data := n.s, n.h.data\n", k.node.name)
		for i, s := range k.node.slots {
			if s.kind == childSlot {
				fmt.Fprintf(&b, "if ref := NodeRef(s.extra[data+%d]); ref != 0 && v(s.node(ref)) { // %s\nreturn true\n}\n", i, s.member)
			} else {
				fmt.Fprintf(&b, "if at := s.extra[data+%d]; at != 0 && visitList(s, at, v) { // %s\nreturn true\n}\n", i, s.member)
			}
		}
		b.WriteString("return false\n}\n")
	}
	return b.String()
}

func (g *generator) convert() string {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString(convertPrelude)
	b.WriteString("func (c *converter) node(n *ast.Node) uint32 {\nif n == nil {\nreturn 0\n}\n")
	b.WriteString("pos, end := int32(n.Pos()), int32(n.End())\nswitch n.Kind {\n")
	b.WriteString("case ast.KindIdentifier:\nreturn uint32(c.b.Identifier(n.Flags, pos, end, n.AsIdentifier().Text))\n")
	seen := map[*node]bool{}
	for _, k := range g.kinds {
		if seen[k.node] {
			continue
		}
		seen[k.node] = true
		kinds := make([]string, len(k.node.kinds))
		for i, kind := range k.node.kinds {
			kinds[i] = "ast.Kind" + kind
		}
		fmt.Fprintf(&b, "case %s:\nd := n.As%s()\nslots := [...]uint32{\n", strings.Join(kinds, ", "), k.node.name)
		for _, s := range k.node.slots {
			fmt.Fprintf(&b, "c.%s(%s),\n", [...]string{"node", "list", "modifiers", "raw"}[s.kind], s.read)
		}
		b.WriteString("}\nreturn uint32(c.b.Node(n.Kind, n.Flags, n.ModifierFlags(), pos, end, slots[:]))\n")
	}
	b.WriteString("}\nreturn uint32(c.b.Node(n.Kind, n.Flags, n.ModifierFlags(), pos, end, nil))\n}\n")
	return b.String()
}

const convertPrelude = `import "github.com/microsoft/TypeScript/tsc/internal/ast"

// Convert builds a Store from a Pointer AST in post-order. It follows exactly
// the children that the Pointer ForEachChild visits, so JSDoc is not converted.
func Convert(file *ast.SourceFile, fileIndex uint32) *Store {
	c := &converter{b: NewBuilder(file.Text(), fileIndex)}
	c.node(file.AsNode())
	return c.b.Finish()
}

type converter struct {
	b     *Builder
	elems []NodeRef // stack of the elements of the lists under construction
}

func (c *converter) elements(pos, end int32, nodes []*ast.Node) uint32 {
	mark := len(c.elems)
	for _, n := range nodes {
		ref := NodeRef(c.node(n))
		c.elems = append(c.elems, ref)
	}
	at := c.b.List(pos, end, c.elems[mark:])
	c.elems = c.elems[:mark]
	return at
}

func (c *converter) list(l *ast.NodeList) uint32 {
	if l == nil {
		return 0
	}
	return c.elements(int32(l.Pos()), int32(l.End()), l.Nodes)
}

func (c *converter) modifiers(l *ast.ModifierList) uint32 {
	if l == nil {
		return 0
	}
	return c.list(&l.NodeList)
}

// A raw list has no Loc of its own.
func (c *converter) raw(nodes []*ast.Node) uint32 {
	if nodes == nil {
		return 0
	}
	return c.elements(0, 0, nodes)
}

`

func write(name, src string) {
	formatted, err := format.Source([]byte(src))
	if err != nil {
		os.WriteFile(filepath.Join(outDir, name), []byte(src), 0o644)
		log.Fatalf("%s: %v", name, err)
	}
	if err := os.WriteFile(filepath.Join(outDir, name), formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}
